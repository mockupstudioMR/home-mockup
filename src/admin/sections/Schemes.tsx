function useRoomFilter(terms: Term[]) {
  const rooms = terms.filter((x) => x.facet === "room_type" && x.status === "active");
  const living = rooms.find((r) => /living/i.test(r.label));
  const [room, setRoom] = useState("");
  useEffect(() => {
    if (!room && living) setRoom(living.id);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [living?.id]);
  return { rooms, room, setRoom };
}

