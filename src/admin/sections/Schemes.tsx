/** First scan image a scheme was seen in, zoomed onto the piece. */
function useSchemeShots(schemeId: string | undefined, limit = 1) {
  return useQuery({
    queryKey: ["scheme-shots", schemeId, limit],
    enabled: !!schemeId,
    queryFn: async () => {
      const { data } = await supabase
        .from("detected_pieces")
        .select("id, box, ingest_items(storage_path, source_url, batch_id, ingest_batches(name))")
        .eq("scheme_id", schemeId!)
        .order("confidence", { ascending: false })
        .limit(limit);
      return (data ?? []) as unknown as { id: string; box: Box | null; ingest_items: { storage_path: string | null; source_url: string | null; batch_id: string; ingest_batches: { name: string } | null } | null }[];
    },
    staleTime: 5 * 60_000,
  });
}

export function Shot({ path, url, box, alt }: { path?: string | null; url?: string | null; box?: Box | null; alt: string }) {
  const { data: src } = useScanImage(path, url);
  return src ? <img src={src} alt={alt} style={zoomTo(box)} /> : null;
}

export function SchemeImg({ id, alt }: { id: string; alt: string }) {
  const { data } = useSchemeShots(id);
  const s = data?.[0];
  return s ? <Shot path={s.ingest_items?.storage_path} url={s.ingest_items?.source_url} box={s.box} alt={alt} /> : null;
}

const nameOf = (s: Scheme, t: (id: string | null) => Term | undefined) => s.label || t(s.category_id)?.label || "Scheme";

