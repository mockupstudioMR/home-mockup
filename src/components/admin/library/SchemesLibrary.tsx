import { useMemo, useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Plus, RefreshCw } from "lucide-react";
import { supabase } from "@/integrations/supabase/client";
import type { Tables } from "@/integrations/supabase/types";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Checkbox } from "@/components/ui/checkbox";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Dialog, DialogContent, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { useToast } from "@/hooks/use-toast";
import { StatusBadge, TermChip, facetLabel, useTerms } from "./shared";

type Scheme = Tables<"furniture_schemes">;
type Combination = Tables<"scheme_combinations">;
const ANY = "__any";
const SOURCE_LABEL: Record<string, string> = { ai_extracted: "AI-saved", curated: "Confirmed", catalog: "From catalogue", user: "From users" };
const SIGNAL_LABEL: Record<string, string> = {
  curated: "Curated by admin",
  bought_together: "Bought together",
  expert_approved: "Expert approved",
  kept_in_design: "Kept in a design",
  liked: "Liked",
  generated: "Generated by AI, no reaction",
  changed_in_design: "Changed in a design",
  disliked: "Disliked",
  expert_rejected: "Expert rejected",
};

export default function SchemesLibrary() {
  const [tab, setTab] = useState<"schemes" | "combinations">("schemes");
  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <h2 className="text-3xl font-extrabold tracking-tight">Schemes &amp; combinations</h2>
          <p className="mt-2 max-w-2xl text-muted-foreground">
            Every piece described the same way: category · colour · style · material · tags. Combinations are two or more schemes that work together.
          </p>
        </div>
        <div className="inline-flex rounded-xl bg-muted p-1" role="tablist">
          {(["schemes", "combinations"] as const).map((t) => (
            <button
              key={t}
              type="button"
              role="tab"
              aria-selected={tab === t}
              onClick={() => setTab(t)}
              className={`min-h-[40px] rounded-lg px-4 text-sm font-semibold capitalize ${tab === t ? "bg-background shadow" : "text-muted-foreground"}`}
            >
              {t}
            </button>
          ))}
        </div>
      </div>
      {tab === "schemes" ? <SchemesTab /> : <CombinationsTab />}
    </div>
  );
}

function SchemesTab() {
  const { toast } = useToast();
  const qc = useQueryClient();
  const { data: terms } = useTerms();
  const [category, setCategory] = useState(ANY);
  const [style, setStyle] = useState(ANY);
  const [source, setSource] = useState(ANY);
  const [status, setStatus] = useState("active");
  const [selected, setSelected] = useState<string | null>(null);
  const [creating, setCreating] = useState(false);
  const [draft, setDraft] = useState<Record<string, string>>({});

  const t = (id: string | null) => (id ? terms?.byId.get(id) : undefined);
  const active = (facet: string) => terms?.list.filter((x) => x.facet === facet && x.status === "active") ?? [];

  const { data } = useQuery({
    queryKey: ["admin-schemes", category, style, source, status],
    queryFn: async () => {
      let q = supabase.from("furniture_schemes").select("*, furniture_scheme_tags(term_id)").order("created_at", { ascending: false }).limit(300);
      if (category !== ANY) q = q.eq("category_id", category);
      if (style !== ANY) q = q.eq("style_id", style);
      if (source !== ANY) q = q.eq("source", source);
      if (status !== ANY) q = q.eq("status", status);
      const { data: schemes, error } = await q;
      if (error) throw error;
      const ids = (schemes ?? []).map((s) => s.id);
      const [{ data: members }, { data: links }] = await Promise.all([
        ids.length ? supabase.from("scheme_combination_members").select("scheme_id, combination_id").in("scheme_id", ids) : Promise.resolve({ data: [] }),
        ids.length ? supabase.from("product_scheme_links").select("scheme_id, product_id").in("scheme_id", ids) : Promise.resolve({ data: [] }),
      ]);
      const combos = new Map<string, number>();
      (members ?? []).forEach((m: { scheme_id: string }) => combos.set(m.scheme_id, (combos.get(m.scheme_id) ?? 0) + 1));
      const products = new Map<string, number>();
      (links ?? []).forEach((l: { scheme_id: string }) => products.set(l.scheme_id, (products.get(l.scheme_id) ?? 0) + 1));
      return { schemes: schemes ?? [], combos, products };
    },
  });

  const setSchemeStatus = useMutation({
    mutationFn: async ({ id, status }: { id: string; status: "active" | "retired" }) => {
      const { error } = await supabase.from("furniture_schemes").update({ status }).eq("id", id);
      if (error) throw error;
    },
    onSuccess: () => qc.invalidateQueries({ queryKey: ["admin-schemes"] }),
  });

  const confirm = useMutation({
    mutationFn: async (id: string) => {
      const { error } = await supabase.from("furniture_schemes").update({ source: "curated" }).eq("id", id);
      if (error) throw error;
    },
    onSuccess: () => qc.invalidateQueries({ queryKey: ["admin-schemes"] }),
  });

  const create = useMutation({
    mutationFn: async () => {
      if (!draft.category) throw new Error("A scheme needs a category.");
      const { data: auth } = await supabase.auth.getUser();
      const { error } = await supabase.from("furniture_schemes").insert({
        category_id: draft.category,
        color_id: draft.color || null,
        style_id: draft.style || null,
        material_id: draft.material || null,
        label: draft.label || null,
        source: "curated",
        created_by: auth.user?.id ?? null,
      });
      if (error) throw error;
    },
    onSuccess: () => {
      setCreating(false);
      setDraft({});
      qc.invalidateQueries({ queryKey: ["admin-schemes"] });
      toast({ title: "Scheme added" });
    },
    onError: (e: Error) =>
      toast({
        title: "Could not add the scheme",
        description: e.message.includes("duplicate") ? "A scheme with exactly this description already exists." : e.message,
        variant: "destructive",
      }),
  });

  const schemes = data?.schemes ?? [];
  const sel = schemes.find((s) => s.id === selected);

  return (
    <>
      <div className="flex flex-wrap items-end gap-3">
        {[
          ["Category", category, setCategory, active("category")],
          ["Style", style, setStyle, active("style")],
        ].map(([label, value, set, list]) => (
          <div key={label as string} className="space-y-1">
            <Label className="text-xs">{label as string}</Label>
            <Select value={value as string} onValueChange={set as (v: string) => void}>
              <SelectTrigger className="w-48"><SelectValue /></SelectTrigger>
              <SelectContent>
                <SelectItem value={ANY}>Any</SelectItem>
                {(list as { id: string; label: string }[]).map((x) => <SelectItem key={x.id} value={x.id}>{x.label}</SelectItem>)}
              </SelectContent>
            </Select>
          </div>
        ))}
        <div className="space-y-1">
          <Label className="text-xs">Source</Label>
          <Select value={source} onValueChange={setSource}>
            <SelectTrigger className="w-44"><SelectValue /></SelectTrigger>
            <SelectContent>
              <SelectItem value={ANY}>All</SelectItem>
              {Object.entries(SOURCE_LABEL).map(([k, l]) => <SelectItem key={k} value={k}>{l}</SelectItem>)}
            </SelectContent>
          </Select>
        </div>
        <div className="space-y-1">
          <Label className="text-xs">Status</Label>
          <Select value={status} onValueChange={setStatus}>
            <SelectTrigger className="w-36"><SelectValue /></SelectTrigger>
            <SelectContent>
              <SelectItem value="active">Active</SelectItem>
              <SelectItem value="retired">Retired</SelectItem>
              <SelectItem value={ANY}>All</SelectItem>
            </SelectContent>
          </Select>
        </div>
        <Button className="ml-auto" onClick={() => setCreating(true)}><Plus className="mr-2 h-4 w-4" /> New scheme</Button>
      </div>

      <div className="flex flex-wrap items-start gap-6">
        <div className="grid min-w-0 flex-[999_1_520px] gap-4 sm:grid-cols-2 xl:grid-cols-3">
          {schemes.length === 0 && <p className="text-muted-foreground">No schemes match. Scan some designs to grow the library.</p>}
          {schemes.map((s) => (
            <button
              key={s.id}
              type="button"
              onClick={() => setSelected(s.id)}
              className={`space-y-3 rounded-2xl border bg-card p-4 text-left ${selected === s.id ? "border-2 border-primary" : ""}`}
            >
              <div className="flex items-start justify-between gap-2">
                <p className="font-bold">{s.label || t(s.category_id)?.label}</p>
                <StatusBadge status={s.source === "ai_extracted" ? "waiting" : "saved"}>{SOURCE_LABEL[s.source] ?? s.source}</StatusBadge>
              </div>
              <div className="flex flex-wrap gap-1">
                <TermChip term={t(s.color_id)} />
                <TermChip term={t(s.style_id)} />
                <TermChip term={t(s.material_id)} />
                {(s.furniture_scheme_tags as { term_id: string }[]).map((x) => <TermChip key={x.term_id} term={t(x.term_id)} />)}
              </div>
              <p className="text-xs font-semibold text-muted-foreground">
                In {data?.combos.get(s.id) ?? 0} combinations · {data?.products.get(s.id) ?? 0} products
              </p>
            </button>
          ))}
        </div>

        {sel && (
          <Card className="min-w-0 flex-[1_1_320px]">
            <CardHeader>
              <CardTitle>{sel.label || t(sel.category_id)?.label}</CardTitle>
              <CardDescription>{SOURCE_LABEL[sel.source]} · added {new Date(sel.created_at).toLocaleDateString()}</CardDescription>
            </CardHeader>
            <CardContent className="space-y-4">
              <div className="flex flex-wrap gap-1.5">
                {(["category", "color", "style", "material"] as const).map((f) => (
                  <TermChip key={f} facet={f} term={t(sel[`${f}_id`])} />
                ))}
              </div>
              <SchemeCombinations schemeId={sel.id} />
              <div className="flex flex-wrap gap-2">
                {sel.source === "ai_extracted" && <Button size="sm" onClick={() => confirm.mutate(sel.id)}>Confirm</Button>}
                {sel.status === "active" ? (
                  <Button size="sm" variant="outline" onClick={() => setSchemeStatus.mutate({ id: sel.id, status: "retired" })}>Retire</Button>
                ) : (
                  <Button size="sm" variant="outline" onClick={() => setSchemeStatus.mutate({ id: sel.id, status: "active" })}>Make active</Button>
                )}
              </div>
            </CardContent>
          </Card>
        )}
      </div>

      <Dialog open={creating} onOpenChange={setCreating}>
        <DialogContent>
          <DialogHeader><DialogTitle>New scheme</DialogTitle></DialogHeader>
          <div className="space-y-3">
            {(["category", "color", "style", "material"] as const).map((f) => (
              <div key={f} className="grid grid-cols-[100px_1fr] items-center gap-3">
                <Label>{facetLabel[f]}</Label>
                <Select value={draft[f] ?? ""} onValueChange={(v) => setDraft((d) => ({ ...d, [f]: v }))}>
                  <SelectTrigger><SelectValue placeholder={f === "category" ? "Required" : "Optional"} /></SelectTrigger>
                  <SelectContent>{active(f).map((x) => <SelectItem key={x.id} value={x.id}>{x.label}</SelectItem>)}</SelectContent>
                </Select>
              </div>
            ))}
            <div className="grid grid-cols-[100px_1fr] items-center gap-3">
              <Label htmlFor="scheme-label">Name</Label>
              <Input id="scheme-label" placeholder="Optional, e.g. Plum curved velvet sofa" value={draft.label ?? ""} onChange={(e) => setDraft((d) => ({ ...d, label: e.target.value }))} />
            </div>
          </div>
          <DialogFooter><Button onClick={() => create.mutate()} disabled={create.isPending}>Add scheme</Button></DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  );
}

function SchemeCombinations({ schemeId }: { schemeId: string }) {
  const { data } = useQuery({
    queryKey: ["scheme-combos", schemeId],
    queryFn: async () => {
      const { data: m } = await supabase.from("scheme_combination_members").select("combination_id").eq("scheme_id", schemeId);
      const ids = (m ?? []).map((x) => x.combination_id);
      if (!ids.length) return [];
      const { data: scores } = await supabase.from("mv_combination_scores").select("combination_id, name, score, member_count").in("combination_id", ids);
      return (scores ?? []).sort((a, b) => Number(b.score) - Number(a.score));
    },
  });
  return (
    <div>
      <p className="mb-1 text-sm font-semibold text-muted-foreground">Combinations it is in</p>
      {(data ?? []).length === 0 ? (
        <p className="text-sm text-muted-foreground">None yet.</p>
      ) : (
        <ul className="divide-y text-sm">
          {(data ?? []).map((c) => (
            <li key={c.combination_id} className="flex justify-between py-2">
              <span>{c.name ?? "Unnamed"} · {c.member_count} pieces</span>
              <span className="font-bold">{Number(c.score).toFixed(2)}</span>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

function CombinationsTab() {
  const { toast } = useToast();
  const qc = useQueryClient();
  const { data: terms } = useTerms();
  const [roomType, setRoomType] = useState(ANY);
  const [building, setBuilding] = useState(false);
  const [pick, setPick] = useState<string[]>([]);
  const [combName, setCombName] = useState("");
  const [combRoom, setCombRoom] = useState("");
  const t = (id: string | null) => (id ? terms?.byId.get(id) : undefined);

  const { data } = useQuery({
    queryKey: ["admin-combinations", roomType],
    queryFn: async () => {
      let q = supabase.from("scheme_combinations").select("*, scheme_combination_members(scheme_id, furniture_schemes(category_id, color_id))").order("created_at", { ascending: false }).limit(200);
      if (roomType !== ANY) q = q.eq("room_type_id", roomType);
      const { data: combos, error } = await q;
      if (error) throw error;
      const ids = (combos ?? []).map((c) => c.id);
      const [{ data: scores }, { data: signals }] = await Promise.all([
        ids.length ? supabase.from("mv_combination_scores").select("combination_id, score").in("combination_id", ids) : Promise.resolve({ data: [] }),
        ids.length ? supabase.from("combination_signals").select("combination_id, signal").in("combination_id", ids) : Promise.resolve({ data: [] }),
      ]);
      const score = new Map<string, number>((scores ?? []).map((s: { combination_id: string | null; score: number | null }) => [s.combination_id ?? "", Number(s.score ?? 0)]));
      const sig = new Map<string, Record<string, number>>();
      (signals ?? []).forEach((s: { combination_id: string; signal: string }) => {
        const r = sig.get(s.combination_id) ?? {};
        r[s.signal] = (r[s.signal] ?? 0) + 1;
        sig.set(s.combination_id, r);
      });
      return { combos: (combos ?? []) as (Combination & { scheme_combination_members: { scheme_id: string; furniture_schemes: { category_id: string; color_id: string | null } | null }[] })[], score, sig };
    },
  });

  const { data: allSchemes } = useQuery({
    queryKey: ["all-active-schemes"],
    enabled: building,
    queryFn: async () => {
      const { data } = await supabase.from("furniture_schemes").select("*").eq("status", "active").limit(1000);
      return (data ?? []) as Scheme[];
    },
  });

  const setCombStatus = useMutation({
    mutationFn: async ({ id, status }: { id: string; status: "active" | "pinned" | "retired" }) => {
      const { error } = await supabase.from("scheme_combinations").update({ status }).eq("id", id);
      if (error) throw error;
    },
    onSuccess: () => qc.invalidateQueries({ queryKey: ["admin-combinations"] }),
  });

  const refreshScores = useMutation({
    mutationFn: async () => {
      const { error } = await supabase.rpc("admin_refresh_scores");
      if (error) throw error;
    },
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ["admin-combinations"] });
      toast({ title: "Scores refreshed" });
    },
    onError: (e: Error) => toast({ title: "Could not refresh", description: e.message, variant: "destructive" }),
  });

  const build = useMutation({
    mutationFn: async () => {
      if (pick.length < 2) throw new Error("Pick at least two schemes.");
      const { data: auth } = await supabase.auth.getUser();
      const { data: comb, error } = await supabase
        .from("scheme_combinations")
        .insert({ name: combName || null, room_type_id: combRoom || null, source: "curated", created_by: auth.user?.id ?? null })
        .select("id")
        .single();
      if (error) throw error;
      const { error: mErr } = await supabase.from("scheme_combination_members").insert(pick.map((scheme_id) => ({ combination_id: comb.id, scheme_id })));
      if (mErr) {
        await supabase.from("scheme_combinations").delete().eq("id", comb.id);
        throw mErr;
      }
      await supabase.from("combination_signals").insert({ combination_id: comb.id, signal: "curated", note: "built by admin" });
    },
    onSuccess: () => {
      setBuilding(false);
      setPick([]);
      setCombName("");
      qc.invalidateQueries({ queryKey: ["admin-combinations"] });
      toast({ title: "Combination added" });
    },
    onError: (e: Error) =>
      toast({ title: "Could not add", description: e.message.includes("duplicate") ? "This set already exists for that room type." : e.message, variant: "destructive" }),
  });

  const rooms = terms?.list.filter((x) => x.facet === "room_type" && x.status === "active") ?? [];
  const sorted = useMemo(
    () => [...(data?.combos ?? [])].sort((a, b) => (data?.score.get(b.id) ?? 0) - (data?.score.get(a.id) ?? 0)),
    [data],
  );

  return (
    <div className="flex flex-wrap items-start gap-6">
      <div className="min-w-0 flex-[999_1_560px] space-y-4">
        <div className="flex flex-wrap items-end gap-3">
          <div className="space-y-1">
            <Label className="text-xs">Room type</Label>
            <Select value={roomType} onValueChange={setRoomType}>
              <SelectTrigger className="w-48"><SelectValue /></SelectTrigger>
              <SelectContent>
                <SelectItem value={ANY}>Any</SelectItem>
                {rooms.map((r) => <SelectItem key={r.id} value={r.id}>{r.label}</SelectItem>)}
              </SelectContent>
            </Select>
          </div>
          <Button variant="outline" onClick={() => refreshScores.mutate()} disabled={refreshScores.isPending}>
            <RefreshCw className="mr-2 h-4 w-4" /> Refresh scores
          </Button>
          <Button className="ml-auto" onClick={() => setBuilding(true)}><Plus className="mr-2 h-4 w-4" /> Build a combination</Button>
        </div>
        <div className="overflow-x-auto rounded-2xl border bg-card">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Combination</TableHead>
                <TableHead>Pieces</TableHead>
                <TableHead>Signals</TableHead>
                <TableHead>Score</TableHead>
                <TableHead>Status</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {sorted.length === 0 && (
                <TableRow><TableCell colSpan={5} className="text-muted-foreground">No combinations yet.</TableCell></TableRow>
              )}
              {sorted.map((c) => (
                <TableRow key={c.id}>
                  <TableCell>
                    <p className="font-semibold">{c.name ?? "Unnamed"}</p>
                    <p className="text-xs text-muted-foreground">{t(c.room_type_id)?.label ?? "Any room"} · {t(c.style_id)?.label ?? "Any style"}</p>
                  </TableCell>
                  <TableCell>
                    <div className="flex max-w-xs flex-wrap gap-1">
                      {c.scheme_combination_members.map((m) => (
                        <TermChip key={m.scheme_id} term={t(m.furniture_schemes?.category_id ?? null)} />
                      ))}
                    </div>
                  </TableCell>
                  <TableCell>
                    <div className="flex max-w-xs flex-wrap gap-1 text-xs font-bold">
                      {Object.entries(data?.sig.get(c.id) ?? {}).map(([s, n]) => (
                        <span key={s} className={`rounded-md px-2 py-0.5 ${["disliked", "changed_in_design", "expert_rejected"].includes(s) ? "bg-red-100 text-red-800" : "bg-primary/10 text-primary"}`}>
                          {s.replace(/_/g, " ")} {n}
                        </span>
                      ))}
                    </div>
                  </TableCell>
                  <TableCell className="font-bold">{(data?.score.get(c.id) ?? 0).toFixed(2)}</TableCell>
                  <TableCell>
                    <Select value={c.status} onValueChange={(v) => setCombStatus.mutate({ id: c.id, status: v as "active" | "pinned" | "retired" })}>
                      <SelectTrigger className="h-9 w-28" aria-label="Status"><SelectValue /></SelectTrigger>
                      <SelectContent>
                        <SelectItem value="active">Active</SelectItem>
                        <SelectItem value="pinned">Pinned</SelectItem>
                        <SelectItem value="retired">Retired</SelectItem>
                      </SelectContent>
                    </Select>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </div>
        <p className="text-sm text-muted-foreground">Scores change when you refresh them. Pinned combinations are always offered for their room type.</p>
      </div>

      <SignalWeights />

      <Dialog open={building} onOpenChange={setBuilding}>
        <DialogContent className="max-h-[85vh] overflow-y-auto">
          <DialogHeader><DialogTitle>Build a combination</DialogTitle></DialogHeader>
          <div className="space-y-3">
            <Input aria-label="Combination name" placeholder="Name, e.g. Plum & emerald lounge" value={combName} onChange={(e) => setCombName(e.target.value)} />
            <Select value={combRoom} onValueChange={setCombRoom}>
              <SelectTrigger><SelectValue placeholder="Room type" /></SelectTrigger>
              <SelectContent>{rooms.map((r) => <SelectItem key={r.id} value={r.id}>{r.label}</SelectItem>)}</SelectContent>
            </Select>
            <p className="text-sm font-semibold">Pick two or more schemes ({pick.length} picked)</p>
            <div className="max-h-72 space-y-1 overflow-y-auto rounded-xl border p-2">
              {(allSchemes ?? []).map((s) => (
                <label key={s.id} className="flex cursor-pointer items-center gap-3 rounded-lg p-2 hover:bg-muted">
                  <Checkbox checked={pick.includes(s.id)} onCheckedChange={(c) => setPick((p) => (c ? [...p, s.id] : p.filter((x) => x !== s.id)))} />
                  <span className="text-sm">
                    {[s.category_id, s.color_id, s.style_id, s.material_id].map((id) => t(id)?.label).filter(Boolean).join(" · ")}
                  </span>
                </label>
              ))}
            </div>
          </div>
          <DialogFooter><Button disabled={pick.length < 2 || build.isPending} onClick={() => build.mutate()}>Add combination</Button></DialogFooter>
        </DialogContent>
      </Dialog>
    </div>
  );
}

function SignalWeights() {
  const { toast } = useToast();
  const qc = useQueryClient();
  const [edits, setEdits] = useState<Record<string, number>>({});
  const { data } = useQuery({
    queryKey: ["signal-weights"],
    queryFn: async () => {
      const { data, error } = await supabase.from("signal_weights").select("*");
      if (error) throw error;
      return data.sort((a, b) => Number(b.weight) - Number(a.weight));
    },
  });
  const save = useMutation({
    mutationFn: async () => {
      for (const [signal, weight] of Object.entries(edits)) {
        const { error } = await supabase.from("signal_weights").update({ weight }).eq("signal", signal as Tables<"signal_weights">["signal"]);
        if (error) throw error;
      }
      await supabase.rpc("admin_refresh_scores");
    },
    onSuccess: () => {
      setEdits({});
      qc.invalidateQueries({ queryKey: ["signal-weights"] });
      qc.invalidateQueries({ queryKey: ["admin-combinations"] });
      toast({ title: "Weights saved and scores refreshed" });
    },
    onError: (e: Error) => toast({ title: "Could not save weights", description: e.message, variant: "destructive" }),
  });

  return (
    <Card className="min-w-0 flex-[1_1_320px]">
      <CardHeader>
        <CardTitle>Signal weights</CardTitle>
        <CardDescription>How much each signal counts toward a combination&apos;s score.</CardDescription>
      </CardHeader>
      <CardContent className="space-y-1">
        {(data ?? []).map((w) => {
          const v = edits[w.signal] ?? Number(w.weight);
          return (
            <div key={w.signal} className="flex items-center justify-between gap-3 border-b py-2 last:border-0">
              <span className="text-sm">{SIGNAL_LABEL[w.signal] ?? w.signal}</span>
              <span className="flex items-center gap-1">
                <Button size="icon" variant="outline" className="h-9 w-9" aria-label="Lower" onClick={() => setEdits((e) => ({ ...e, [w.signal]: Math.max(-5, v - 1) }))}>−</Button>
                <output className={`w-8 text-center font-extrabold ${v < 0 ? "text-red-700" : ""}`}>{v}</output>
                <Button size="icon" variant="outline" className="h-9 w-9" aria-label="Raise" onClick={() => setEdits((e) => ({ ...e, [w.signal]: Math.min(5, v + 1) }))}>+</Button>
              </span>
            </div>
          );
        })}
        <Button className="mt-3 w-full" disabled={!Object.keys(edits).length || save.isPending} onClick={() => save.mutate()}>
          Save weights &amp; refresh
        </Button>
      </CardContent>
    </Card>
  );
}
